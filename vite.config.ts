import { copyFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { defineConfig, type Plugin, type ResolvedConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { buildContent, ContentError } from './scripts/content.ts'

const root = fileURLToPath(new URL('.', import.meta.url))
const contentDir = path.join(root, 'content')

/**
 * Runs the content pipeline (scripts/content.ts) inside Vite.
 *
 * - `vite build`: once, before bundling, without drafts. Public files are
 *   copied at the end of the build, so the generated JSON makes it into dist.
 * - `vite dev`: once on start, then again whenever anything under content/
 *   changes. The app listens for `content:update` and refetches through
 *   TanStack Query, so an edited post updates in place without a reload.
 *   A content error goes to Vite's error overlay instead of killing the server.
 */
function contentPlugin(): Plugin {
  let config: ResolvedConfig

  return {
    name: 'personal-site:content',
    configResolved(resolved) {
      config = resolved
    },

    async buildStart() {
      if (config.command !== 'build') return
      try {
        await buildContent({ root, base: config.base, includeDrafts: false })
      } catch (error) {
        // Strip the stack: for a content mistake it's noise, and the message
        // already names the file and field.
        if (error instanceof ContentError) this.error(error.message)
        throw error
      }
    },

    async configureServer(server) {
      const run = async () => {
        try {
          const { counts } = await buildContent({ root, base: config.base, includeDrafts: true })
          config.logger.info(
            `content: ${Object.entries(counts)
              .map(([name, count]) => `${count} ${name}`)
              .join(', ')}`,
            { timestamp: true },
          )
          server.ws.send({ type: 'custom', event: 'content:update' })
        } catch (error) {
          if (!(error instanceof ContentError)) throw error
          config.logger.error(error.message, { timestamp: true })
          server.ws.send({
            type: 'error',
            err: { message: error.message, stack: '', plugin: 'personal-site:content' },
          })
        }
      }

      await run()

      // The CMS's "local repository" mode and editors that save via a temp
      // file both fire bursts of events; one rebuild per burst is plenty.
      let timer: ReturnType<typeof setTimeout> | undefined
      server.watcher.add(contentDir)
      server.watcher.on('all', (_event, file) => {
        if (!path.resolve(file).startsWith(contentDir + path.sep)) return
        clearTimeout(timer)
        timer = setTimeout(() => void run(), 150)
      })
    },
  }
}

/**
 * GitHub Pages has no SPA rewrite, but it does serve 404.html for any unknown
 * path. Making that a copy of index.html means a deep link or a refresh on
 * /raving/some-post boots the app, and the router takes it from there.
 */
function pagesFallback(): Plugin {
  let outDir: string
  return {
    name: 'personal-site:pages-fallback',
    apply: 'build',
    configResolved(resolved) {
      outDir = path.resolve(resolved.root, resolved.build.outDir)
    },
    async closeBundle() {
      await copyFile(path.join(outDir, 'index.html'), path.join(outDir, '404.html'))
    },
  }
}

export default defineConfig({
  // "/" for a <username>.github.io repo, "/<repo>/" for any other. The deploy
  // workflow sets this from the repository name.
  base: process.env.SITE_BASE ?? '/',
  plugins: [react(), contentPlugin(), pagesFallback()],
  define: {
    'import.meta.env.VITE_BUILD_ID': JSON.stringify(Date.now().toString(36)),
  },
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    // Generated by the content plugin; letting Vite react to them too would
    // trigger a full reload on top of the in-place refetch.
    watch: { ignored: ['**/public/data/**', '**/public/img/**'] },
  },
})
